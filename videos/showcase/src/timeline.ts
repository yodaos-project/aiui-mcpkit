export const SOURCE_BEAT0 = 0.00044288440896655105;
export const BEAT_INT = 0.461507402026131;
export const OUTPUT_AUDIO_OFFSET_SEC = 0;
export const beatT = (n: number) =>
  SOURCE_BEAT0 + OUTPUT_AUDIO_OFFSET_SEC + n * BEAT_INT;
